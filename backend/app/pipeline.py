import logging
import threading

from .db import Chunk, Document, SessionLocal
from .indexing import index_chunks
from .ingestion.chunk import chunk_blocks
from .ingestion.extract import extract_blocks

log = logging.getLogger("pipeline")
_ingest_lock = threading.Lock()  # one document at a time


def _ingest(document_id: str, data: bytes) -> None:
    """Runs in a background task. 'ready' is set only after indexing succeeds."""
    with SessionLocal() as db:
        doc = db.get(Document, document_id)
        doc.status = "processing"
        db.commit()
        try:
            title, blocks, low_text = extract_blocks(data)
            if low_text:
                raise ValueError("Very little extractable text; PDF may be scanned (OCR not supported yet)")
            chunks = chunk_blocks(blocks)
            if not chunks:
                raise ValueError("No usable text chunks produced")
            rows = [Chunk(document_id=document_id, **c.__dict__) for c in chunks]
            db.add_all(rows)
            db.flush()  # ids are generated by default=new_id at construction time
            index_chunks(rows)
            doc.title = title
            doc.status = "ready"
            db.commit()
        except Exception as e:
            log.exception("Ingestion failed for %s", document_id)
            db.rollback()
            doc = db.get(Document, document_id)
            doc.status = "failed"
            doc.error = str(e)[:500]
            db.commit()


def ingest_document(document_id: str, data: bytes) -> None:
    with _ingest_lock:
        _ingest(document_id, data)